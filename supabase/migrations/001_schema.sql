-- Internal: record one answer, update the Mistake Notebook. Returns the effect.
create or replace function public._apply_answer(p_attempt uuid, p_user uuid, p_qid uuid, p_selected text)
returns text language plpgsql security definer set search_path = public as $$
declare
  v_correct text;
  v_dropped boolean;
  v_effect  text;
  v_existing public.attempt_answers;
begin
  if p_selected is null or p_selected not in ('A','B','C','D','E') then return null; end if;

  select * into v_existing from public.attempt_answers where attempt_id = p_attempt and question_id = p_qid;
  if found then return v_existing.notebook_effect; end if;  -- already recorded (practice mode)

  select correct_option, is_dropped into v_correct, v_dropped from public.questions where id = p_qid;
  if v_correct is null or v_dropped then return null; end if;

  if p_selected = v_correct then
    delete from public.mistakes where user_id = p_user and question_id = p_qid;
    if found then v_effect := 'cleared'; end if;
  else
    if exists (select 1 from public.mistakes where user_id = p_user and question_id = p_qid) then
      update public.mistakes
         set times_missed = times_missed + 1, last_selected = p_selected, last_missed_at = now()
       where user_id = p_user and question_id = p_qid;
      v_effect := 'missed_again';
    else
      insert into public.mistakes (user_id, question_id, last_selected) values (p_user, p_qid, p_selected);
      v_effect := 'added';
    end if;
  end if;

  insert into public.attempt_answers (attempt_id, user_id, question_id, selected_option, is_correct, notebook_effect)
  values (p_attempt, p_user, p_qid, p_selected, p_selected = v_correct, v_effect);
  return v_effect;
end $$;
revoke all on function public._apply_answer(uuid, uuid, uuid, text) from public, anon, authenticated;

-- Practice mode: lock in one answer immediately.
create or replace function public.record_practice_answer(p_attempt uuid, p_question uuid, p_selected text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  a public.quiz_attempts;
  v_effect text;
  v_correct text;
begin
  select * into a from public.quiz_attempts where id = p_attempt;
  if a.id is null or a.user_id <> auth.uid() then raise exception 'Attempt not found'; end if;
  if a.status <> 'in_progress' or a.mode <> 'practice' then raise exception 'Attempt is not an open practice quiz'; end if;
  if not (p_question = any (a.question_ids)) then raise exception 'Question not in this quiz'; end if;

  v_effect := public._apply_answer(p_attempt, a.user_id, p_question, p_selected);
  update public.quiz_attempts
     set responses = responses || jsonb_build_object(p_question::text, jsonb_build_object('selected', p_selected))
   where id = p_attempt;
  select correct_option into v_correct from public.questions where id = p_question;
  return jsonb_build_object('is_correct', p_selected = v_correct, 'correct_option', v_correct, 'effect', v_effect);
end $$;

-- Submit and score a quiz. Exam mode answers are recorded here.
create or replace function public.submit_attempt(p_attempt uuid, p_responses jsonb, p_time_taken int)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  a public.quiz_attempts;
  qid uuid;
  v_correct int; v_wrong int; v_total int; v_score numeric;
begin
  select * into a from public.quiz_attempts where id = p_attempt for update;
  if a.id is null or a.user_id <> auth.uid() then raise exception 'Attempt not found'; end if;
  if a.status = 'submitted' then
    return jsonb_build_object('already_submitted', true, 'score', a.score);
  end if;

  foreach qid in array a.question_ids loop
    perform public._apply_answer(p_attempt, a.user_id, qid, p_responses -> qid::text ->> 'selected');
  end loop;

  select count(*) filter (where is_correct), count(*) filter (where not is_correct)
    into v_correct, v_wrong
    from public.attempt_answers where attempt_id = p_attempt;
  v_total := cardinality(a.question_ids);
  v_score := round(v_correct * a.positive_marks - v_wrong * a.negative_marks, 2);

  update public.quiz_attempts set
    responses      = coalesce(p_responses, responses),
    status         = 'submitted',
    submitted_at   = now(),
    time_taken_sec = greatest(0, least(coalesce(p_time_taken, 0), 86400)),
    correct_count  = v_correct,
    wrong_count    = v_wrong,
    skipped_count  = v_total - v_correct - v_wrong,
    total_count    = v_total,
    score          = v_score
  where id = p_attempt;

  return jsonb_build_object('score', v_score, 'correct', v_correct, 'wrong', v_wrong,
                            'skipped', v_total - v_correct - v_wrong, 'total', v_total);
end $$;

-- Build a randomised quiz (dropped questions are always excluded).
create or replace function public.build_quiz(
  p_subject_ids int[] default null,
  p_topic_ids   int[] default null,
  p_exam_ids    int[] default null,
  p_count       int   default 20,
  p_source      text  default 'all',
  p_high_priority_only boolean default false
) returns uuid[] language sql stable security invoker set search_path = public as $$
  select coalesce(array_agg(id), '{}') from (
    select q.id
    from public.questions q
    where not q.is_dropped
      and (p_subject_ids is null or cardinality(p_subject_ids) = 0 or q.subject_id = any (p_subject_ids))
      and (p_topic_ids   is null or cardinality(p_topic_ids)   = 0 or q.topic_id   = any (p_topic_ids))
      and (p_exam_ids    is null or cardinality(p_exam_ids)    = 0 or q.exam_id    = any (p_exam_ids))
      and (
        p_source = 'all'
        or (p_source = 'bookmarks' and exists (select 1 from public.bookmarks b where b.user_id = auth.uid() and b.question_id = q.id))
        or (p_source = 'mistakes'  and exists (select 1 from public.mistakes  m where m.user_id = auth.uid() and m.question_id = q.id))
      )
      and (not p_high_priority_only or public.high_priority(q))
    order by random()
    limit least(greatest(coalesce(p_count, 20), 1), 150)
  ) s;
$$;

-- How many live questions match a filter (shown in the quiz builder).
create or replace function public.count_questions(
  p_subject_ids int[] default null, p_topic_ids int[] default null, p_exam_ids int[] default null
) returns int language sql stable security invoker set search_path = public as $$
  select count(*)::int from public.questions q
  where not q.is_dropped
    and (p_subject_ids is null or cardinality(p_subject_ids) = 0 or q.subject_id = any (p_subject_ids))
    and (p_topic_ids   is null or cardinality(p_topic_ids)   = 0 or q.topic_id   = any (p_topic_ids))
    and (p_exam_ids    is null or cardinality(p_exam_ids)    = 0 or q.exam_id    = any (p_exam_ids));
$$;

