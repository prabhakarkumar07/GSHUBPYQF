-- Community stats: % of students who got each question right.
-- Uses each student's FIRST attempt at a question so repeats don't skew it.
create or replace function public.get_question_stats(p_ids uuid[])
returns table (question_id uuid, attempts int, correct int, option_counts jsonb)
language sql stable security definer set search_path = public as $$
  with firsts as (
    select distinct on (user_id, question_id) user_id, question_id, is_correct, selected_option
    from public.attempt_answers
    where question_id = any (p_ids)
    order by user_id, question_id, answered_at
  ), per_opt as (
    select question_id, selected_option, count(*) as n from firsts group by 1, 2
  )
  select f.question_id,
         count(*)::int,
         count(*) filter (where f.is_correct)::int,
         (select jsonb_object_agg(p.selected_option, p.n) from per_opt p where p.question_id = f.question_id)
  from firsts f
  group by f.question_id;
$$;

-- Student's own accuracy by subject/topic (heat map)
create or replace function public.get_my_accuracy()
returns table (subject_id int, topic_id int, attempted int, correct int)
language sql stable security invoker set search_path = public as $$
  select q.subject_id, q.topic_id, count(*)::int, count(*) filter (where aa.is_correct)::int
  from public.attempt_answers aa
  join public.questions q on q.id = aa.question_id
  where aa.user_id = auth.uid()
  group by q.subject_id, q.topic_id;
$$;

-- Mistake counts per subject/topic (notebook dashboard)
create or replace function public.get_my_mistake_summary()
returns table (subject_id int, topic_id int, mistakes int, high_priority int)
language sql stable security invoker set search_path = public as $$
  select q.subject_id, q.topic_id, count(*)::int, count(*) filter (where public.high_priority(q))::int
  from public.mistakes m
  join public.questions q on q.id = m.question_id
  where m.user_id = auth.uid()
  group by q.subject_id, q.topic_id;
$$;

-- Admin analytics
create or replace function public.admin_analytics()
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_today date := (now() at time zone 'Asia/Kolkata')::date;
  v_min int;
  result jsonb;
begin
  if not public.is_admin() then raise exception 'Admins only'; end if;
  select min_stats_attempts into v_min from public.app_settings where id = 1;

  select jsonb_build_object(
    'total_users',      (select count(*) from public.profiles),
    'new_users_7d',     (select count(*) from public.profiles where created_at > now() - interval '7 days'),
    'live_questions',   (select count(*) from public.questions where not is_dropped),
    'dropped_questions',(select count(*) from public.questions where is_dropped),
    'quizzes_submitted',(select count(*) from public.quiz_attempts where status = 'submitted'),
    'answers_recorded', (select count(*) from public.attempt_answers),
    'dau_today', (select count(distinct user_id) from public.quiz_attempts
                  where (updated_at at time zone 'Asia/Kolkata')::date = v_today),
    'dau_series', (
      select coalesce(jsonb_agg(jsonb_build_object('day', d::date, 'users', coalesce(u.n, 0)) order by d), '[]'::jsonb)
      from generate_series(v_today - 13, v_today, interval '1 day') d
      left join (
        select (updated_at at time zone 'Asia/Kolkata')::date as day, count(distinct user_id) as n
        from public.quiz_attempts group by 1
      ) u on u.day = d::date
    ),
    'most_missed', (
      select coalesce(jsonb_agg(row_to_json(t)), '[]'::jsonb) from (
        select q.id, left(regexp_replace(q.question_en, '<[^>]+>', ' ', 'g'), 160) as question,
               s.name_en as subject, count(*) as attempts,
               round(100.0 * count(*) filter (where aa.is_correct) / count(*), 1) as correct_pct
        from public.attempt_answers aa
        join public.questions q on q.id = aa.question_id
        join public.subjects s on s.id = q.subject_id
        group by q.id, s.name_en
        having count(*) >= greatest(v_min, 1)
        order by correct_pct asc, attempts desc
        limit 15
      ) t
    ),
    'feedback_count', (select count(*) from public.feedback)
  ) into result;
  return result;
end $$;

