-- ---------------------------------------------------------------------
-- Questions
-- options: [{"key":"A","en":"...","hi":"..."}, ...]  (2–5 items, A–E)
-- question/solution fields hold sanitised HTML (tables, images allowed)
-- ---------------------------------------------------------------------
create table public.questions (
  id               uuid primary key default gen_random_uuid(),
  exam_id          int references public.exams(id) on delete set null,
  year             int,
  subject_id       int not null references public.subjects(id) on delete restrict,
  topic_id         int references public.topics(id) on delete set null,
  difficulty       text not null default 'medium' check (difficulty in ('easy','medium','hard')),
  question_en      text not null,
  question_hi      text,
  options          jsonb not null
                   check (jsonb_typeof(options) = 'array' and jsonb_array_length(options) between 2 and 5),
  correct_option   text not null check (correct_option in ('A','B','C','D','E')),
  solution_en      text,
  solution_hi      text,
  is_dropped       boolean not null default false,   -- dropped/cancelled by BPSC
  is_high_priority boolean not null default false,   -- manual flag by staff
  theme            text,                             -- repeated-theme tag, e.g. 'champaran'
  source           text not null default 'pyq',      -- 'pyq' | 'sample' | 'current_affairs' | 'test_series'
  created_by       uuid references auth.users(id) on delete set null default auth.uid(),
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index on public.questions (subject_id, topic_id) where not is_dropped;
create index on public.questions (exam_id);
create index on public.questions (theme);

create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;

create trigger questions_touch before update on public.questions
  for each row execute function public.touch_updated_at();

-- Computed column (PostgREST exposes it as `high_priority` on questions):
-- a question is high priority when staff flagged it, OR its theme has been
-- asked in 2+ different exams/years (a repeated theme).
create or replace function public.high_priority(q public.questions)
returns boolean language sql stable as $$
  select q.is_high_priority
      or (q.theme is not null and (
            select count(distinct coalesce(q2.exam_id::text, q2.year::text, q2.id::text))
            from public.questions q2
            where q2.theme = q.theme and not q2.is_dropped
          ) >= 2);
$$;

